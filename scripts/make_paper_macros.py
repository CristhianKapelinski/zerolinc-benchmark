"""Generate the paper's % RESULTS MACROS block from the stored runs/protocol."""

import json
import sys
from collections import Counter
from pathlib import Path

from zerolinc.data import load_incidents

RUNS = Path("results/runs")
REPORT = Path("results/report")


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}"


def main() -> int:
    out_path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(
        "/mnt/win_ssd/paper-zerolinc/macros.tex")
    incs = load_incidents("data/185_incidentes_anon.csv")
    dist = Counter(i.label for i in incs)
    runs = [json.loads(p.read_text()) for p in RUNS.glob("*.json")]
    models = [r for r in runs if not r["run_id"].startswith("baseline")]
    best = max(models, key=lambda r: r["metrics"]["accuracy"])
    best_f1 = max(models, key=lambda r: r["metrics"]["macro_f1"])
    majority = next(r for r in runs if r["run_id"] == "baseline__majority")
    keyword = next(r for r in runs if r["run_id"] == "baseline__keyword")
    gli = json.loads((RUNS / "gliclass-modern-base-v3.0__en-event.json").read_text())
    deb = json.loads(
        (RUNS / "deberta-v3-large-zeroshot-v2.0__en-desc-kw__subject.json").read_text())

    seeds = sorted(int(p.stem.split("seed")[1]) for p in REPORT.glob("protocol_seed*.json"))
    protos = [json.loads((REPORT / f"protocol_seed{s}.json").read_text()) for s in seeds]
    ens = [p["ensemble_rank"] for p in protos if "ensemble_rank" in p]
    ens_accs = [e["test"]["accuracy"] for e in ens]
    ens_f1s = [e["test"]["macro_f1"] for e in ens]
    ens_ps = [e["mcnemar_vs_majority_on_test"]["p_value"] for e in ens]
    nli_accs = [p["families"]["nli"]["test"]["accuracy"] for p in protos]
    p42 = next(p for p in protos if p["seed"] == 42)
    best_per = best["metrics"]["per_class"]

    n_pt = sum(1 for i in incs
               if len(__import__("re").findall(r"\b(que|para|como|não|nao|foi|rede)\b", i.text))
               > len(__import__("re").findall(r"\b(the|and|from|your|network|this)\b", i.text)))

    m = {
        "NIncidents": str(len(incs)),
        "NRaw": "185",
        "NCatFive": str(dist["CAT5"]),
        "PctCatFive": pct(dist["CAT5"] / len(incs)),
        "NPtDominant": str(n_pt),
        "NEnDominant": str(len(incs) - n_pt),
        "NModelRuns": str(len(models)),
        "NModels": "10",
        "NConfigs": "8",
        "NViews": "4",
        "MajorityAcc": pct(majority["metrics"]["accuracy"]),
        "MajorityMacroF": f"{majority['metrics']['macro_f1']:.2f}",
        "KeywordAcc": pct(keyword["metrics"]["accuracy"]),
        "KeywordMacroF": f"{keyword['metrics']['macro_f1']:.2f}",
        "BestAcc": pct(best["metrics"]["accuracy"]),
        "BestRun": best["run_id"].replace("_", "\\_"),
        "BestMacroF": f"{best_f1['metrics']['macro_f1']:.2f}",
        "BestMacroFAcc": pct(best_f1["metrics"]["accuracy"]),
        "DebertaAcc": pct(deb["metrics"]["accuracy"]),
        "DebertaMacroF": f"{deb['metrics']['macro_f1']:.2f}",
        "DebertaWall": f"{deb['wall_seconds']:.0f}",
        "DebertaEnergy": f"{deb.get('gpu_energy_wh', 0):.1f}",
        "GliAcc": pct(gli["metrics"]["accuracy"]),
        "GliWall": f"{gli['wall_seconds']:.1f}",
        "GliEnergy": f"{gli.get('gpu_energy_wh', 0):.2f}",
        "GliVram": f"{gli.get('peak_vram_mb', 0) / 1024:.1f}",
        "ProtoNDev": str(p42["n_dev"]),
        "ProtoNTest": str(p42["n_test"]),
        "ProtoMajTest": pct(p42["majority_test_accuracy"]),
        "ProtoNliTestAcc": pct(p42["families"]["nli"]["test"]["accuracy"]),
        "ProtoNliTestMacroF": f"{p42['families']['nli']['test']['macro_f1']:.2f}",
        "ProtoNliMcnemarP": f"{p42['families']['nli']['mcnemar_vs_majority_on_test']['p_value']:.2f}",
        "EnsMeanAcc": pct(sum(ens_accs) / len(ens_accs)),
        "EnsMinAcc": pct(min(ens_accs)),
        "EnsMaxAcc": pct(max(ens_accs)),
        "EnsMeanMacroF": f"{sum(ens_f1s) / len(ens_f1s):.2f}",
        "EnsPMin": f"{min(ens_ps):.2f}",
        "EnsPMax": f"{max(ens_ps):.2f}",
        "NliMeanTestAcc": pct(sum(nli_accs) / len(nli_accs)),
        "NSeeds": str(len(seeds)),
        "CatFiveF": f"{best_per['CAT5']['f1']:.2f}",
        "CatFiveN": str(best_per["CAT5"]["support"]),
        "CatThreeRecall": f"{best_per['CAT3']['recall']:.2f}",
        "CatThreeN": str(best_per["CAT3"]["support"]),
        "CatTwelveRecall": f"{best_per['CAT12']['recall']:.2f}",
        "CatTwelveN": str(best_per["CAT12"]["support"]),
    }
    lines = ["% RESULTS MACROS (generated by scripts/make_paper_macros.py; do not edit)"]
    for k, v in m.items():
        lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    out_path.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(m)} macros to {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
